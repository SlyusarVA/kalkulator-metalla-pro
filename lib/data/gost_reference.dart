// Поиск справки по коду ГОСТа
GostReference? findGostReference(String code) {
  // Точное совпадение
  for (final r in gostReferences) {
    if (r.code == code) return r;
  }
  // Частичное совпадение
  for (final r in gostReferences) {
    if (code.contains(r.code) || r.code.contains(code)) return r;
  }
  return null;
}
